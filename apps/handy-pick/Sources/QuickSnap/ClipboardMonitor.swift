import AppKit
import QuickSnapCore

@MainActor final class ClipboardMonitor {
    private(set) var history = ClipboardHistory()
    var onChange: (([ClipboardHistory.Entry]) -> Void)?
    private var timer: Timer?
    private var changeCount = 0
    private let pasteboard: NSPasteboard
    init(pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }
    func start() {
        stop()
        changeCount = pasteboard.changeCount // Do not import content from before launch.
        timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer!, forMode: .common)
    }
    func stop() { timer?.invalidate(); timer = nil }
    func poll() {
        let current = pasteboard.changeCount
        guard current != changeCount else { return }
        changeCount = current
        let types = pasteboard.types ?? []
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !types.contains(where: { excluded.contains($0.rawValue) }) else { return }
        let content: ClipboardHistory.Content?
        if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: { types.contains($0) }),
           let data = pasteboard.data(forType: type), data.count <= history.maximumBytes {
            content = .image(data, type: type.rawValue)
        } else if let text = pasteboard.string(forType: .string) { content = .text(text) }
        else { content = nil }
        guard pasteboard.changeCount == current, let content else { return }
        if history.insert(content) { onChange?(history.entries) }
    }
    @discardableResult func select(_ id: UUID) -> Bool {
        guard let entry = history.entries.first(where: { $0.id == id }) else { return false }
        pasteboard.clearContents()
        let result: Bool
        switch entry.content {
        case .text(let text): result = pasteboard.setString(text, forType: .string)
        case .image(let data, let type): result = pasteboard.setData(data, forType: .init(type))
        }
        poll()
        return result
    }
    func remove(_ id: UUID) { history.remove(id); onChange?(history.entries) }
    func clear() {
        // Clearing the history does not destroy the user's current system clipboard.
        changeCount = pasteboard.changeCount
        history.clear(); onChange?(history.entries)
    }
}
